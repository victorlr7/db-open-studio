const dictionaries: Record<Locale, Record<TranslationKey, string>> = { en, es, ca };

export function normalizeLocale(value: unknown): Locale {
  return value === "es" || value === "ca" ? value : "en";
}

export function translate(locale: unknown, key: TranslationKey, params: TranslationParams = {}) {
  const template = dictionaries[normalizeLocale(locale)][key] ?? en[key];
  return template.replace(/\{(\w+)\}/g, (_, param: string) => String(params[param] ?? ""));
}

export function createTranslator(locale: unknown) {
  return (key: TranslationKey, params?: TranslationParams) => translate(locale, key, params);
}

export type Translator = ReturnType<typeof createTranslator>;
